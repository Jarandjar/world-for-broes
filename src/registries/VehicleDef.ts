import { ItemRarity } from './ItemDef';

export type VehicleClass =
  | 'scooter'
  | 'compact'
  | 'sedan'
  | 'van'
  | 'pickup'
  | 'truck'
  | 'bus'
  | 'heavy'
  | 'weird'
  | 'boat'
  | 'rail'
  | 'air'
  | 'trailer';

export type VehicleRole =
  | 'scout'
  | 'silent'
  | 'hauler'
  | 'base'
  | 'utility'
  | 'fighter'
  | 'terrain_specialist'
  | 'trailer';

export type VehicleWeightClass = 'light' | 'medium' | 'heavy';

export interface VehicleDef {
  id: string;
  name: string;
  rarity: ItemRarity;
  vehicleClass: VehicleClass;
  role: VehicleRole;
  weightClass: VehicleWeightClass;
  seats: number;
  trunkSlots: number;
  topSpeed: number; // in meters/second (e.g. 14 m/s is ~50 km/h)
  acceleration: number; // m/s^2
  handling: number; // steering responsiveness multiplier
  fuelCapacity: number; // in liters (0 = no engine)
  fuelConsumptionRate: number; // liters per 100m driven (0 = no engine)
  offroadGripMultiplier: number; // 0.2 to 1.0
  hornType: 'sad_trombone' | 'bike_horn' | 'ice_cream_jingle' | 'quack' | 'standard' | 'monster_roar' | 'rooster' | 'bell' | 'siren' | 'organ';
  engineNoiseRadius: number; // radius in meters that alerts zombies
  quirk: string;
  hasFreezer?: boolean;
  hasCookingGriddle?: boolean;
  floatsOnWater?: boolean;
  towsTrailer?: boolean;
  isTrailer?: boolean;
  isAircraft?: boolean;
  altitudeBands?: ('ground' | 'low' | 'high')[];
  canWinch?: boolean;
}

